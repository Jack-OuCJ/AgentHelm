"""CLI model commands and independent desktop App role bindings."""
import re
import shlex

from _workspace import CONFIG, ROOT, write

MARKDOWN = CONFIG / "models.md"
EXECUTOR_ROLES = ('fact', 'hard', 'chore', 'writing', 'visual', 'simplify', 'aesthetic')
AGENTS = ROOT / '.claude/agents'


def select(config, role):
    active = [c for c in role['candidates'] if config['providers'][c.split(':')[0]]]
    return active if role.get('mode', 'first') == 'all' else active[:1]


def command(config, candidate, research=False):
    provider, model, *effort = candidate.split(':')
    spec = config['commands'][provider]
    template = spec.get('default_template', provider) if model == 'default' else spec['template']
    return template.format(model=shlex.quote(model), effort=shlex.quote(effort[0]) if effort else '',
                                   research_flags=spec.get('research_flags', '') if research else '').strip()


def validate(config):
    validate_app(config)
    for name, role in config['roles'].items():
        if role.get('mode', 'first') not in ('first', 'all') or role.get('research', False) not in (True, False, 'split'):
            raise ValueError('Invalid role mode or research setting')
        for candidate in role['candidates']:
            parts = candidate.split(':')
            if len(parts) not in (2, 3) or not all(parts) or parts[0] not in config['providers']:
                raise ValueError('Invalid candidate: ' + candidate)
            if parts[1] != 'default' and '{effort}' in config['commands'][parts[0]]['template'] and len(parts) != 3:
                raise ValueError(f'Role {name}: candidate {candidate} requires effort for its command template')
            research = role.get('research', False)
            for mode in (True, False) if research == 'split' else (research,):
                command(config, candidate, mode)


def generate(config):
    lines = ['<!-- Generated by bin/models from local roles.toml. -->', '',
             '| Role | Tier | Active model | Command |', '|---|---|---|---|']
    for name, role in config['roles'].items():
        active = select(config, role)
        commands = []
        for candidate in active:
            def code(research=False):
                return '`' + command(config, candidate, research).replace('|', '\\|') + '`'
            commands.append('Research: ' + code(True) + '<br>Implementation: ' + code(False)
                            if role.get('research') == 'split' else code(role.get('research', False)))
        commands = '<br>'.join(commands)
        lines.append(f'| {name} ({role["desc"]}) | {role["tier"]} | {"<br>".join(active) or "unavailable"} | {commands or "—"} |')
    lines += ['', 'App 参数为新会话的请求值，default 表示目标 App 原生默认；inherit 表示 CCD Executor 沿用所属 Lead 的所选设置或请求值；'
              '实际生效值由宿主验证。', '',
              '| Role | App entry | Requested model | Model source | Requested effort | Effort source |',
              '|---|---|---|---|---|---|']
    for name in config['roles']:
        for entry in ('app.codex', 'app.ccd'):
            binding = resolve_app(config, name, entry)
            unset = 'inherit' if entry == 'app.ccd' and name in EXECUTOR_ROLES else 'default'
            values = [name, entry, binding['model'] or unset, binding['sources']['model'],
                      binding['effort'] or unset, binding['sources']['effort']]
            lines.append('| ' + ' | '.join(value.replace('|', '\\|') for value in values) + ' |')
    write(MARKDOWN, '\n'.join(lines) + '\n')


def validate_app(config):
    """Validate App configuration shape; model availability belongs to the host."""
    def table(value, path, keys=None):
        if not isinstance(value, dict):
            raise ValueError(f'{path} must be a table')
        if keys is not None and set(value) - set(keys):
            raise ValueError(f'{path}: unknown fields {", ".join(sorted(set(value) - set(keys)))}')
        return value

    app = table(config.get('app', {}), 'app', ('defaults',))
    defaults = table(app.get('defaults', {}), 'app.defaults', ('codex', 'ccd'))
    groups = [(defaults, 'app.defaults')]
    for name, role in table(config.get('roles', {}), 'roles').items():
        role = table(role, f'roles.{name}')
        groups.append((table(role.get('app', {}), f'roles.{name}.app', ('codex', 'ccd')),
                       f'roles.{name}.app'))
    for group, path in groups:
        for app_name, binding in group.items():
            binding_path = f'{path}.{app_name}'
            for field, value in table(binding, binding_path, ('model', 'effort')).items():
                if (not isinstance(value, str) or not value or value != value.strip()
                        or any(ord(character) < 32 or ord(character) == 127 for character in value)):
                    raise ValueError(f'{binding_path}.{field} must be a nonempty string without surrounding whitespace or control characters')


def resolve_app(config, role, entry):
    if entry not in ('app.codex', 'app.ccd'):
        raise ValueError('Invalid App entry: ' + str(entry))
    validate_app(config)
    if role not in config.get('roles', {}):
        raise ValueError('Unknown role: ' + str(role))
    app = entry.split('.')[1]
    # A CCD subagent without its own model or effort inherits the Lead session, never app defaults.
    inherit = app == 'ccd' and role in EXECUTOR_ROLES
    defaults = config.get('app', {}).get('defaults', {}).get(app, {})
    override = config['roles'][role].get('app', {}).get(app, {})
    result = {'entry': entry, 'role': role, 'sources': {}}
    for field in ('model', 'effort'):
        if field in override:
            value, source = override[field], f'roles.{role}.app.{app}'
        elif field in defaults and not inherit:
            value, source = defaults[field], f'app.defaults.{app}'
        else:
            value, source = 'default', 'lead-inherit' if inherit else 'native-default'
        result[field] = None if value == 'default' else value
        result['sources'][field] = source
    return result


def ccd_agent_path(role):
    return AGENTS / f'agenthelm-{role}.md'


def ccd_agent(config, role):
    """Render the CCD subagent definition that pins one Executor role's model and effort."""
    binding = resolve_app(config, role, 'app.ccd')
    for field in ('model', 'effort'):
        if binding[field] is not None and not re.fullmatch(r'[A-Za-z0-9._/\[\]-]+', binding[field]):
            raise ValueError(f'roles.{role}.app.ccd.{field} cannot be written to a CCD agent definition')
    lines = ['---', f'name: agenthelm-{role}',
             f'description: AgentHelm {role} Executor. Use only when an AgentHelm request names '
             f'subagent_type agenthelm-{role}.',
             '# Generated by bin/models from local roles.toml; restart the Lead session after changes.',
             'model: ' + (binding['model'] or 'inherit')]
    if binding['effort'] is not None:
        lines.append('effort: ' + binding['effort'])
    lines += ['---', '',
              f'你是 AgentHelm {role} Executor。按委派 prompt 执行：只在授权任务目录工作，只写授权文件，'
              '直接完成委派任务和验收后报告真实结果，无需启动握手或等待本地绑定；父会话事后核验运行证据。'
              '不创建下层代理或会话，不修改全局配置。', '']
    return '\n'.join(lines)


def write_ccd_agents(config):
    for role in EXECUTOR_ROLES:
        if role in config.get('roles', {}):
            write(ccd_agent_path(role), ccd_agent(config, role))
