"""Two-scope working memory: notes are the source; bin/kb index generates each MEMORY.md.

context, read, check and fingerprint only read files. They never fetch URLs, call models or
write notes, hashes, statuses, dates or indexes. A matching hash proves only that a declared
dependency file is unchanged; it does not prove completeness, conditions or live state.
"""
import datetime
import hashlib
import json
import os
import re
import stat
import sys

from _app_sessions import guarded_path
from _workspace import ROOT

FIELDS = ('id', 'scope', 'kind', 'status', 'summary', 'verified_at', 'valid_when', 'sources',
          'dependencies', 'superseded_by')
REQUIRED = FIELDS[:8]
KINDS = ('decision', 'finding', 'pointer')
STATUSES = ('active', 'stale', 'conflict', 'superseded')
INDEX_LINES, INDEX_BYTES, NOTE_BYTES, TEXT_LIMIT, SHOWN, WIDTH = 60, 8192, 16384, 200, 10, 240
MARKER = '<!-- Generated by bin/kb index from memory notes; edit the notes, then rerun bin/kb index. -->'
KEBAB = r'[a-z0-9]+(?:-[a-z0-9]+)*'


def controls(text):
    """Control characters and Unicode line separators would split one-line fields and indexes."""
    return any(ord(c) < 32 or c in '\x7f\x85\u2028\u2029' for c in text)


def clean(raw, cli=False):
    """Return a normalized workspace-relative path before any filesystem access.

    Note metadata must already be relative and normalized. CLI arguments may also be absolute
    inside this workspace and may contain '.' or empty parts. '..' is never accepted.
    """
    if not isinstance(raw, str) or not raw or raw.startswith('~') or controls(raw):
        raise ValueError(f'invalid workspace path: {raw!r}')
    if os.path.isabs(raw):
        prefix = str(ROOT) + os.sep
        if not cli:
            raise ValueError(f'absolute path is not allowed: {raw}')
        if not raw.startswith(prefix):
            raise ValueError(f'path outside workspace: {raw}')
        raw = raw[len(prefix):]
    parts = [part for part in raw.split('/') if not (cli and part in ('', '.'))]
    if not parts or any(part in ('', '.', '..') for part in parts):
        raise ValueError(f'path must stay in the workspace without ., .. or empty parts: {raw}')
    return '/'.join(parts)


def open_file(relative):
    """Open a workspace regular file without following a symbolic link in any component."""
    path = guarded_path(ROOT / relative)
    descriptor = os.open(path, os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK)
    try:
        if not stat.S_ISREG(os.fstat(descriptor).st_mode):
            raise ValueError(f'not a regular file: {relative}')
        return os.fdopen(descriptor, 'rb')
    except BaseException:
        os.close(descriptor)
        raise


def read_bounded(relative, limit):
    with open_file(relative) as stream:
        return stream.read(limit + 1)


def digest(relative):
    with open_file(relative) as stream:
        value = hashlib.sha256()
        for block in iter(lambda: stream.read(1 << 20), b''):
            value.update(block)
    return value.hexdigest()


def unique(pairs):
    keys = [key for key, _ in pairs]
    if len(set(keys)) != len(keys):
        raise ValueError('duplicate JSON key')
    return dict(pairs)


def decode(text, field):
    try:
        return json.loads(text, object_pairs_hook=unique)
    except ValueError as error:
        raise ValueError(f'{field} must be one-line JSON ({error})') from None


def valid_date(text):
    try:
        return bool(re.fullmatch(r'\d{4}-\d{2}-\d{2}', text) and datetime.date.fromisoformat(text))
    except ValueError:
        return False


def local_source(source):
    """Split an optional :LINE or :START-END suffix from a workspace-relative source."""
    match = re.fullmatch(r'(.+?)(?::(\d+)(?:-(\d+))?)?', source)
    if not match:
        raise ValueError(f'invalid source: {source!r}')
    start, end = int(match[2] or 1), int(match[3] or match[2] or 1)
    if start < 1 or end < start:
        raise ValueError(f'invalid line range in source: {source}')
    return clean(match[1])


def parse(relative, scope, text):
    """Validate restricted one-line frontmatter; every problem carries its line number."""
    note = dict.fromkeys(FIELDS[:7] + FIELDS[9:], '')
    note.update(path=relative, text=text, lines={}, sources=[], local=[], dependencies={}, errors=[])

    def error(key, message):
        note['errors'].append(f'{relative}:{note["lines"].get(key, 1)}: {message}')

    lines = text.split('\n')
    if lines[0] != '---' or '---' not in lines[1:len(FIELDS) + 2]:
        error(None, f'note must open with --- and close with --- after at most {len(FIELDS)} one-line fields')
        return note
    values = {}
    for number, line in enumerate(lines[1:lines.index('---', 1)], 2):
        match = re.fullmatch(r'([a-z_]+): (.*\S.*)', line)
        if not match or controls(line):
            note['errors'].append(f'{relative}:{number}: frontmatter needs one "key: value" per line')
        elif match[1] not in FIELDS or match[1] in values:
            note['errors'].append(f'{relative}:{number}: {"duplicate" if match[1] in values else "unknown"} field {match[1]}')
        else:
            values[match[1]] = match[2].strip()
            note['lines'][match[1]] = number
    for key in REQUIRED:
        if key not in values:
            error(key, f'missing {key}')
    note.update((key, values.get(key, '')) for key in note['lines'] if key not in ('sources', 'dependencies'))
    stem = relative.rsplit('/', 1)[1][:-3]
    if not re.fullmatch(KEBAB, stem):
        error(None, 'note file name must be <kebab-case id>.md')
    if note['id'] and note['id'] != stem:
        error('id', 'id must equal the file name')
    if note['scope'] and note['scope'] != scope:
        error('scope', f'scope must be {scope} in this directory')
    for key, allowed in (('kind', KINDS), ('status', STATUSES)):
        if note[key] and note[key] not in allowed:
            error(key, f'{key} must be one of {", ".join(allowed)}')
    for key in ('summary', 'valid_when'):
        if len(note[key]) > TEXT_LIMIT:
            error(key, f'{key} exceeds {TEXT_LIMIT} characters')
    if note['verified_at'] and not valid_date(note['verified_at']):
        error('verified_at', 'verified_at must be a YYYY-MM-DD date')
    if 'sources' in values:
        try:
            sources = decode(values['sources'], 'sources')
            if not isinstance(sources, list) or not sources or not all(isinstance(s, str) for s in sources):
                raise ValueError('sources must be a nonempty JSON array of strings')
            for source in sources:
                if re.match(r'https?://', source):
                    if not re.fullmatch(r'https?://[^\s/?#]+\S*', source):
                        raise ValueError(f'invalid source URL: {source}')
                    continue
                path = local_source(source)
                if path not in note['local']:
                    note['local'].append(path)
            note['sources'] = sources
        except ValueError as problem:
            error('sources', str(problem))
    if 'dependencies' in values:
        try:
            dependencies = decode(values['dependencies'], 'dependencies')
            if not isinstance(dependencies, dict) or not dependencies:
                raise ValueError('dependencies must be a nonempty JSON object of path to SHA-256')
            for path, value in dependencies.items():
                clean(path)
                if not isinstance(value, str) or not re.fullmatch(r'[0-9a-f]{64}', value):
                    raise ValueError(f'dependency {path} needs a lowercase SHA-256 hex digest')
            note['dependencies'] = dependencies
        except ValueError as problem:
            error('dependencies', str(problem))
    elif note['kind'] == 'finding':
        error(None, 'finding requires dependencies')
    if note['status'] == 'superseded' and not note['superseded_by']:
        error('status', 'superseded status requires superseded_by')
    if note['superseded_by'] and note['status'] != 'superseded':
        error('superseded_by', 'superseded_by requires status superseded')
    elif note['superseded_by'] and not re.fullmatch(KEBAB, note['superseded_by']):
        error('superseded_by', 'superseded_by must be a note id in this scope')
    return note


def problems(note):
    """Filesystem validity of a well-formed note: local sources exist, dependency hashes match."""
    found = []
    checks = [('source', path, None) for path in note['local']]
    checks += [('dependency', path, value) for path, value in note['dependencies'].items()]
    for kind, path, expected in checks:
        try:
            if expected is None:
                open_file(path).close()
            elif digest(path) != expected:
                found.append(f'dependency changed: {path}')
        except FileNotFoundError:
            found.append(f'{kind} missing: {path}')
        except (OSError, ValueError) as error:
            found.append(f'{kind} unusable: {path} ({error})')
    return found


def bounded(items):
    """At most SHOWN diagnostic lines of WIDTH characters; omissions are always stated."""
    shown = ['- ' + (item if len(item) <= WIDTH else item[:WIDTH] + '…(truncated)') for item in items[:SHOWN]]
    if len(items) > SHOWN:
        shown.append(f'- … {len(items) - SHOWN} more; run bin/kb memory check')
    return shown


class Scope:
    """Every note of one memory directory, parsed once; nothing here writes to disk."""

    def __init__(self, directory, title):
        self.directory, self.title = directory, title
        self.kind = 'project' if directory == 'memory' else 'task'
        self.index = directory + '/MEMORY.md'
        self.notes, self.errors, self.content = [], [], None
        try:
            with os.scandir(guarded_path(ROOT / directory)) as entries:
                names = sorted(entry.name for entry in entries)
        except FileNotFoundError:
            names = []
        except (OSError, ValueError) as error:
            self.errors.append(f'{directory}:1: unusable memory directory ({error})')
            return
        for name in names:
            if name.endswith('.md') and name != 'MEMORY.md':
                self.load(directory + '/' + name)
        owners = {}
        for note in self.notes:
            if note['id']:
                owners.setdefault(note['id'], []).append(note)
        for ident, group in owners.items():
            for note in group if len(group) > 1 else []:
                others = ', '.join(other['path'] for other in group if other is not note)
                note['errors'].append(f'{note["path"]}:{note["lines"].get("id", 1)}: duplicate id {ident} (also {others})')
        for note in self.notes:
            target = note['superseded_by']
            if note['status'] != 'superseded' or not re.fullmatch(KEBAB, target or '-'):
                continue
            chain, current = [note['id']], target
            while current in owners and current not in chain:
                chain.append(current)
                current = owners[current][0]['superseded_by'] or None
            where = f'{note["path"]}:{note["lines"].get("superseded_by", 1)}'
            if target not in owners:
                note['errors'].append(f'{where}: superseded_by target {target} is not a note in {directory}')
            elif current in chain:
                note['errors'].append(f'{where}: superseded_by cycle {" -> ".join(chain + [current])}')
        if self.notes and not self.invalid():
            lines = [MARKER, f'# Memory index: {title}']
            for note in sorted(self.notes, key=lambda item: item['id']):
                status = 'superseded by ' + note['superseded_by'] if note['status'] == 'superseded' else note['status']
                lines.append(f'- [{note["id"]}]({note["id"]}.md) | {status} | {note["summary"]} | valid_when: {note["valid_when"]}')
            content = '\n'.join(lines) + '\n'
            if len(lines) > INDEX_LINES or len(content.encode()) > INDEX_BYTES:
                self.errors.append(f'{self.index}:1: generated index needs {len(lines)} lines and '
                                   f'{len(content.encode())} bytes; budget {INDEX_LINES} lines and '
                                   f'{INDEX_BYTES} bytes; retire or merge notes')
            else:
                self.content = content

    def load(self, relative):
        try:
            data = read_bounded(relative, NOTE_BYTES)
            if len(data) > NOTE_BYTES:
                raise ValueError(f'note exceeds {NOTE_BYTES} bytes')
            note = parse(relative, self.kind, data.decode('utf-8'))
        except (OSError, ValueError) as error:
            note = parse(relative, self.kind, '')
            note.update(text=None, errors=[f'{relative}:1: unreadable note ({error})'])
        self.notes.append(note)

    def invalid(self):
        return self.errors + [error for note in self.notes for error in note['errors']]

    def state(self):
        """Compare MEMORY.md with the generated catalog without trusting or showing its text."""
        try:
            data = read_bounded(self.index, INDEX_BYTES)
        except FileNotFoundError:
            return 'missing' if self.notes else 'absent'
        except (OSError, ValueError) as error:
            return f'unusable ({error})'
        if not data.startswith(MARKER.encode()):
            return 'hand-written'
        if not self.notes:
            return 'orphaned'
        return 'current' if self.content is not None and data == self.content.encode() else 'stale'

    def describe(self):
        """Startup lines: the catalog plus diagnostics, never note bodies or unchecked old text."""
        lines = [f'### {"项目" if self.kind == "project" else "任务"} {self.index}（笔记路径 {self.directory}/<id>.md）']
        errors = self.invalid()
        if errors:
            return lines + ['诊断：笔记非法或索引超出预算，未展示目录；用 bin/kb memory check 查看全部定位。'] + bounded(errors)
        state = self.state()
        if not self.notes:
            return lines + (['（无笔记）'] if state == 'absent' else [f'（无笔记）诊断：{self.index} {state}，未读取其内容。'])
        if state != 'current':
            lines.append(f'诊断：{self.index} {state}；下列为按笔记在内存中生成的当前目录，未写回；发布请运行 bin/kb index。')
        lines += self.content.split('\n')[2:-1]
        stale = []
        for note in self.notes:
            found = problems(note) if note['status'] == 'active' else []
            if found:
                stale.append(f'{note["path"]}: not effective: stale ({"; ".join(found[:3])}'
                             + (f'; +{len(found) - 3} more' if len(found) > 3 else '') + ')')
        if stale:
            lines += ['诊断：下列声明 active 的笔记来源或依赖已变化，不能直接复用：'] + bounded(stale)
        return lines


def task_directory(raw):
    """Resolve TASK (absolute, workspace-relative or a bare name) to experiments/<task>."""
    raw = str(raw)
    relative = clean(raw if '/' in raw else 'experiments/' + raw, cli=True)
    parts = relative.split('/')
    if len(parts) != 2 or parts[0] != 'experiments' or not guarded_path(ROOT / relative).is_dir():
        raise ValueError(f'task must be an existing experiments/<task> directory: {raw}')
    return relative


def task_names():
    """Direct task directories; symbolic links are not tasks and are never followed."""
    base = ROOT / 'experiments'
    if base.is_symlink() or not base.is_dir():
        return []
    with os.scandir(base) as entries:
        return sorted(entry.name for entry in entries if entry.is_dir(follow_symlinks=False))


def task_scope(relative):
    return Scope(relative + '/memory', 'task ' + relative.split('/')[1])


def context(task=None):
    """Startup catalog: project for a Dispatcher, project and task for a Lead; no note bodies."""
    scopes = [Scope('memory', 'project')] + ([task_scope(task_directory(task))] if task is not None else [])
    lines = ['## 记忆索引（仅目录；复用前用 bin/kb memory read <笔记路径> 打开并核验来源）']
    for scope in scopes:
        lines += scope.describe()
    return '\n'.join(lines) + '\n'


def read(raw):
    """Print one note for review; exit 0 only when it is effective and active."""
    relative = clean(raw, cli=True)
    parts = relative.split('/')
    if (not parts[-1].endswith('.md') or parts[-1] == 'MEMORY.md'
            or not (parts[0] == 'memory' and len(parts) == 2
                    or parts[0] == 'experiments' and len(parts) == 4 and parts[2] == 'memory')):
        raise ValueError('note must be memory/<id>.md or experiments/<task>/memory/<id>.md')
    try:
        open_file(relative).close()
    except FileNotFoundError:
        raise ValueError(f'note not found: {relative}') from None
    scope = Scope('memory', 'project') if len(parts) == 2 else task_scope('/'.join(parts[:2]))
    note = next((item for item in scope.notes if item['path'] == relative), None)
    if note is None:
        raise ValueError(f'note is not part of its memory scope: {relative}; {"; ".join(scope.errors)}')
    if note['errors']:
        state, found = 'invalid', note['errors']
    elif note['status'] != 'active':
        state, found = note['status'], [f'declared status {note["status"]}' + (
            f'; replaced by {scope.directory}/{note["superseded_by"]}.md' if note['superseded_by'] else '')]
    else:
        found = problems(note)
        state = 'stale' if found else 'active'
    if state == 'active':
        lines = ['effective: active; local sources exist and declared dependency hashes match. '
                 'This does not prove completeness, natural-language conditions, permissions or live state.']
    else:
        lines = [f'!!! NOT EFFECTIVE ({state}): shown for review only; do not reuse it as an active '
                 'conclusion before rechecking its sources.'] + ['- ' + item for item in found]
    lines += [f'- scope: {item}' for item in scope.errors]
    if note['text'] is not None:
        lines += [f'----- {relative} -----', note['text'].rstrip('\n')]
    print('\n'.join([f'memory read: {relative}'] + lines))
    return 0 if state == 'active' else 1


ADVICE = {'missing': 'run bin/kb index', 'stale': 'run bin/kb index', 'orphaned': 'run bin/kb index',
          'hand-written': 'convert its entries into notes, then remove it'}


def check(task=None):
    """Structure, scope, paths, budgets, indexes, sources, dependencies and replacement links."""
    names = [task_directory(task)] if task is not None else ['experiments/' + name for name in task_names()]
    scopes = [Scope('memory', 'project')] + [task_scope(name) for name in names]
    issues = []
    for scope in scopes:
        errors = scope.invalid()
        issues += errors
        state = scope.state()
        if not errors and state not in ('current', 'absent'):
            issues.append(f'{scope.index}:1: index {state}; {ADVICE.get(state, "replace it with a generated regular file")}')
        for note in scope.notes if not errors else []:
            if note['status'] in ('stale', 'conflict'):
                issues.append(f'{note["path"]}:{note["lines"]["status"]}: not effective: declared {note["status"]}')
            elif note['status'] == 'active':
                issues += [f'{note["path"]}:1: not effective: {found}' for found in problems(note)]
    total = sum(len(scope.notes) for scope in scopes)
    summary = f'{len(issues)} issue(s)' if issues else 'ok'
    print('\n'.join(issues + [f'memory check: {summary} ({total} notes in {len(scopes)} scopes)']))
    return int(bool(issues))


def fingerprint(paths):
    """Print a dependencies JSON object for regular workspace files; refuse any unsafe path."""
    result, errors = {}, []
    for raw in paths:
        try:
            relative = clean(raw, cli=True)
            result[relative] = digest(relative)
        except FileNotFoundError:
            errors.append(f'file not found: {raw}')
        except (OSError, ValueError) as error:
            errors.append(str(error))
    if errors:
        print('\n'.join('kb memory fingerprint: ' + error for error in errors), file=sys.stderr)
        return 2
    print(json.dumps(dict(sorted(result.items())), ensure_ascii=False))
    return 0


def publication():
    """Prechecked MEMORY.md outputs for bin/kb index: (outputs, published scopes, errors).

    An output of None removes a generated index whose last note was deleted. Hand-written or
    unusable index files are never replaced.
    """
    outputs, published, errors = {}, [], []
    for scope in [Scope('memory', 'project')] + [task_scope('experiments/' + name) for name in task_names()]:
        errors += scope.invalid()
        state = scope.state()
        if scope.notes and (state == 'hand-written' or state.startswith('unusable')):
            errors.append(f'{scope.index}:1: index {state}; refusing to replace it')
        elif scope.content is not None:
            outputs[scope.index] = scope.content
            published.append(scope)
        elif state == 'orphaned':
            outputs[scope.index] = None
    return outputs, published, errors


def main(args):
    """Run one read-only memory command; refused paths or tasks exit 2 without note text."""
    try:
        if args.action == 'context':
            print(context(args.task), end='')
            return 0
        if args.action == 'read':
            return read(args.note)
        if args.action == 'check':
            return check(args.task)
        return fingerprint(args.files)
    except (OSError, ValueError) as error:
        print(f'kb memory {args.action}: {error}', file=sys.stderr)
        return 2
