"""Working-memory contracts through bin/kb and restore entry points, offline with a temporary HOME."""
import json
import os
import subprocess
import unittest

import test_workspace
from test_workspace import snapshot, write_note

MARKER = '<!-- Generated by bin/kb index from memory notes; edit the notes, then rerun bin/kb index. -->'


class MemoryTests(unittest.TestCase):
    tearDown = test_workspace.WorkspaceTests.tearDown
    run_cmd = test_workspace.WorkspaceTests.run_cmd

    def setUp(self):
        test_workspace.WorkspaceTests.setUp(self)
        (self.root / '.agenthelm/config/env').write_text('cli-plain\n')
        self.task = self.root / 'experiments/001-memory'
        (self.task / 'findings').mkdir(parents=True)
        (self.task / 'README.md').write_text('# Memory task\n- id: 001-memory\n- question: Does memory restore?\n')

    def kb(self, *args, code=0):
        result = subprocess.run([str(self.root / 'bin/kb'), *map(str, args)], cwd=self.root, text=True,
                                capture_output=True, env=self.env, timeout=15)
        self.assertEqual(result.returncode, code, result.stdout + result.stderr)
        return result

    def test_two_scopes_generate_catalogs_and_context_never_shows_bodies(self):
        write_note(self.root, 'memory/layout.md', summary='Project layout rule', valid_when='layout unchanged',
                   body='Project body text')
        fingerprint = json.loads(self.kb('memory', 'fingerprint', 'experiments/001-memory/README.md').stdout)
        write_note(self.root, 'experiments/001-memory/memory/probe.md', kind='finding',
                   summary='Task probe result', valid_when='README unchanged',
                   sources=['experiments/001-memory/README.md:2-3'], dependencies=fingerprint, body='Task body text')
        project = self.kb('memory', 'context').stdout
        self.assertIn('memory/MEMORY.md missing', project)
        self.assertIn('- [layout](layout.md) | active | Project layout rule | valid_when: layout unchanged', project)
        self.assertNotIn('Task probe result', project)
        both = self.kb('memory', 'context', '--task', self.task).stdout
        for text in ('Project layout rule', 'Task probe result'):
            self.assertIn(text, both)
        for text in ('Project body text', 'Task body text', MARKER):
            self.assertNotIn(text, both)
        self.assertFalse((self.root / 'memory/MEMORY.md').exists())
        self.kb('index')
        self.assertEqual((self.root / 'memory/MEMORY.md').read_text(), MARKER + '\n# Memory index: project\n'
                         '- [layout](layout.md) | active | Project layout rule | valid_when: layout unchanged\n')
        self.assertEqual((self.task / 'memory/MEMORY.md').read_text(), MARKER + '\n# Memory index: task 001-memory\n'
                         '- [probe](probe.md) | active | Task probe result | valid_when: README unchanged\n')
        self.assertIn('## Memory\n- [project](memory/MEMORY.md)\n'
                      '- [task 001-memory](experiments/001-memory/memory/MEMORY.md)\n',
                      (self.root / 'INDEX.md').read_text())
        self.kb('index', '--check')
        self.assertIn('memory check: ok (2 notes in 2 scopes)', self.kb('memory', 'check').stdout)
        current = self.kb('memory', 'context', '--task', 'experiments/001-memory').stdout
        self.assertNotIn('诊断', current)
        self.assertEqual(self.kb('memory', 'context', '--task', '001-memory').stdout, current)
        read = self.kb('memory', 'read', 'experiments/001-memory/memory/probe.md').stdout
        self.assertIn('effective: active', read)
        self.assertIn('Task body text', read)
        other = self.root / 'experiments/002-other'
        write_note(self.root, 'experiments/002-other/memory/broken.md', scope='project')
        self.assertIn('experiments/002-other/memory/broken.md:3: scope must be task',
                      self.kb('memory', 'check', code=1).stdout)
        self.assertIn('ok (2 notes in 2 scopes)', self.kb('memory', 'check', '--task', self.task).stdout)
        self.assertIn('scope must be task', self.kb('memory', 'check', '--task', other, code=1).stdout)
        self.kb('memory', 'context', '--task', 'experiments/003-missing', code=2)

    def test_startup_and_restore_entries_give_each_role_only_its_catalogs(self):
        write_note(self.root, 'memory/shared.md', summary='Shared project catalog line',
                   body='Shared body never injected')
        write_note(self.root, 'experiments/001-memory/memory/local.md', summary='Local task catalog line',
                   body='Local body never injected')
        self.kb('index')
        views = {
            'dispatcher print': self.run_cmd('bin/dispatch', '--print').stdout,
            'dispatcher hook': self.run_cmd('bin/lead-watch-start', input=json.dumps({
                'cwd': str(self.root), 'source': 'startup'})).stdout,
            'lead prompt': self.run_cmd('bin/spawn-lead', self.task).stdout,
            'lead hook': self.run_cmd('bin/lead-watch-start', input=json.dumps({
                'cwd': str(self.task / 'findings'), 'source': 'startup'})).stdout,
            'lead reload': self.run_cmd('bin/lead-reload', self.task, 'resume').stdout,
            'executor': self.run_cmd('bin/run-executor', self.task, '--role', 'hard', '--print',
                                     input='只读任务目录。').stdout}
        self.assertIn('当前角色：dispatcher', views['dispatcher hook'])
        self.assertIn('当前角色：executor (hard)', views['executor'])
        for name, output in views.items():
            self.assertEqual('Shared project catalog line' in output, name != 'executor', name)
            self.assertEqual('Local task catalog line' in output, name.startswith('lead'), name)
            self.assertNotIn('body never injected', output)
            self.assertNotIn(MARKER, output)
        self.assertNotIn('## Task memory', views['lead reload'])
        self.assertIn('## STATUS', views['lead reload'])
        self.assertFalse(self.log.exists())

    def test_missing_stale_or_hand_written_index_is_diagnosed_without_writing(self):
        note = write_note(self.root, 'memory/rule.md', summary='Original summary')
        self.kb('index')
        note.write_text(note.read_text().replace('Original summary', 'Edited summary'))
        before = snapshot(self.root)
        context = self.kb('memory', 'context').stdout
        self.assertIn('memory/MEMORY.md stale', context)
        self.assertIn('| Edited summary |', context)
        self.assertNotIn('Original summary', context)
        self.assertIn('stale: memory/MEMORY.md', self.kb('index', '--check', code=1).stdout)
        self.assertIn('memory/MEMORY.md:1: index stale', self.kb('memory', 'check', code=1).stdout)
        self.kb('memory', 'read', 'memory/rule.md')
        self.assertEqual(snapshot(self.root), before)
        (self.root / 'memory/MEMORY.md').unlink()
        before = snapshot(self.root)
        self.assertIn('memory/MEMORY.md missing', self.kb('memory', 'context').stdout)
        self.kb('index', '--check', code=1)
        self.assertEqual(snapshot(self.root), before)
        (self.root / 'memory/MEMORY.md').write_text('- hand-written secret entry\n')
        before = snapshot(self.root)
        context = self.kb('memory', 'context').stdout
        self.assertIn('memory/MEMORY.md hand-written', context)
        self.assertIn('| Edited summary |', context)
        self.assertNotIn('secret entry', context)
        self.assertIn('refusing to replace it', self.kb('index', code=1).stdout)
        self.assertIn('convert its entries into notes', self.kb('memory', 'check', code=1).stdout)
        self.assertEqual(snapshot(self.root), before)

    def test_index_is_idempotent_after_summary_edits_and_note_removal(self):
        first = write_note(self.root, 'memory/first.md', summary='First summary')
        second = write_note(self.root, 'memory/second.md', summary='Second summary')
        self.kb('index')
        published = snapshot(self.root)
        self.kb('index')
        self.kb('index', '--check')
        self.assertEqual(snapshot(self.root), published)
        first.write_text(first.read_text().replace('First summary', 'First summary revised'))
        self.kb('index')
        self.assertIn('| First summary revised |', (self.root / 'memory/MEMORY.md').read_text())
        revised = snapshot(self.root)
        self.kb('index')
        self.assertEqual(snapshot(self.root), revised)
        second.unlink()
        self.kb('index')
        catalog = (self.root / 'memory/MEMORY.md').read_text()
        self.assertNotIn('second', catalog)
        self.assertEqual(len(catalog.splitlines()), 3)
        first.unlink()
        self.kb('index')
        self.assertFalse((self.root / 'memory/MEMORY.md').exists())
        self.assertNotIn('memory/MEMORY.md', (self.root / 'INDEX.md').read_text())
        emptied = snapshot(self.root)
        self.kb('index')
        self.kb('index', '--check')
        self.assertEqual(snapshot(self.root), emptied)
        self.assertEqual(self.kb('memory', 'context', '--task', self.task).stdout.count('（无笔记）'), 2)
        self.assertFalse((self.task / 'memory').exists())

    def test_finding_dependencies_detect_change_and_deletion_but_not_unrelated_edits(self):
        source = self.task / 'findings/module.py'
        source.write_text('VALUE = 1\n')
        unrelated = self.task / 'findings/other.py'
        unrelated.write_text('OTHER = 1\n')
        dependencies = json.loads(self.kb('memory', 'fingerprint', source).stdout)
        self.assertEqual(list(dependencies), ['experiments/001-memory/findings/module.py'])
        note = write_note(self.root, 'experiments/001-memory/memory/module-value.md', kind='finding',
                          summary='Module value is one', sources=['experiments/001-memory/findings/module.py:1'],
                          dependencies=dependencies, body='Finding body for review')
        self.kb('index')
        original = note.read_bytes()
        self.assertIn('effective: active', self.kb('memory', 'read', note).stdout)
        unrelated.write_text('OTHER = 2\n')
        self.kb('memory', 'read', note)
        self.kb('memory', 'check')
        source.write_text('VALUE = 2\n')
        read = self.kb('memory', 'read', note, code=1).stdout
        for text in ('NOT EFFECTIVE (stale)', 'dependency changed: experiments/001-memory/findings/module.py',
                     'Finding body for review'):
            self.assertIn(text, read)
        self.assertIn('module-value.md:1: not effective: dependency changed',
                      self.kb('memory', 'check', code=1).stdout)
        context = self.kb('memory', 'context', '--task', self.task).stdout
        self.assertIn('- [module-value](module-value.md) | active | Module value is one', context)
        self.assertIn('module-value.md: not effective: stale (dependency changed', context)
        self.kb('index', '--check')
        source.unlink()
        self.assertIn('dependency missing: experiments/001-memory/findings/module.py',
                      self.kb('memory', 'read', note, code=1).stdout)
        self.assertEqual(note.read_bytes(), original)
        write_note(self.root, 'memory/cited.md', sources=['docs/absent.md', 'https://example.com/spec'])
        self.assertIn('source missing: docs/absent.md', self.kb('memory', 'read', 'memory/cited.md', code=1).stdout)
        write_note(self.root, 'experiments/001-memory/memory/unproved.md', kind='finding')
        self.assertIn('unproved.md:1: finding requires dependencies', self.kb('memory', 'check', code=1).stdout)
        before = snapshot(self.root)
        self.assertIn('nothing was published', self.kb('index', code=1).stdout)
        self.assertEqual(snapshot(self.root), before)

    def test_declared_conflict_supersession_and_cycles(self):
        write_note(self.root, 'memory/new-rule.md', summary='Replacement rule')
        write_note(self.root, 'memory/old-rule.md', status='superseded', superseded_by='new-rule', summary='Old rule')
        disputed = write_note(self.root, 'memory/disputed.md', status='conflict', summary='Disputed rule')
        self.kb('index')
        catalog = (self.root / 'memory/MEMORY.md').read_text()
        self.assertIn('- [old-rule](old-rule.md) | superseded by new-rule | Old rule |', catalog)
        self.assertIn('- [disputed](disputed.md) | conflict | Disputed rule |', catalog)
        old = self.kb('memory', 'read', 'memory/old-rule.md', code=1).stdout
        self.assertIn('NOT EFFECTIVE (superseded)', old)
        self.assertIn('replaced by memory/new-rule.md', old)
        self.assertIn('NOT EFFECTIVE (conflict)', self.kb('memory', 'read', 'memory/disputed.md', code=1).stdout)
        check = self.kb('memory', 'check', code=1).stdout
        self.assertIn('memory/disputed.md:5: not effective: declared conflict', check)
        self.assertNotIn('old-rule', check)
        disputed.unlink()
        self.kb('index')
        self.kb('memory', 'check')
        write_note(self.root, 'memory/loop-a.md', status='superseded', superseded_by='loop-b')
        write_note(self.root, 'memory/loop-b.md', status='superseded', superseded_by='loop-a')
        write_note(self.root, 'memory/orphan.md', status='superseded', superseded_by='ghost')
        write_note(self.root, 'memory/early.md', superseded_by='new-rule')
        before = snapshot(self.root)
        check = self.kb('memory', 'check', code=1).stdout
        for text in ('memory/loop-a.md:10: superseded_by cycle loop-a -> loop-b -> loop-a',
                     'memory/loop-b.md:10: superseded_by cycle loop-b -> loop-a -> loop-b',
                     'memory/orphan.md:10: superseded_by target ghost is not a note in memory',
                     'memory/early.md:10: superseded_by requires status superseded'):
            self.assertIn(text, check)
        self.assertIn('nothing was published', self.kb('index', code=1).stdout)
        context = self.kb('memory', 'context').stdout
        self.assertIn('未展示目录', context)
        self.assertNotIn('Replacement rule', context)
        self.assertEqual(snapshot(self.root), before)

